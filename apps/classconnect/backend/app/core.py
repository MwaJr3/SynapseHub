"""ClassConnect domain logic: session lifecycle, room tokens, schedule conflicts, provider policy."""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import time

# ------------------------------------------------------- session lifecycle ---

TRANSITIONS = {
    "scheduled": {"starting", "cancelled", "failed"},
    "starting": {"live", "failed", "cancelled"},
    "live": {"ended", "failed"},
    "ended": set(),
    "cancelled": set(),
    "failed": {"scheduled"},  # retry: reschedule a failed session
}


class SessionError(ValueError):
    pass


def validate_transition(current: str, target: str) -> None:
    if target not in TRANSITIONS.get(current, set()):
        raise SessionError(f"Illegal session transition '{current}' → '{target}'. Allowed: {sorted(TRANSITIONS.get(current, set()))}.")


# ------------------------------------------------------------- room tokens ---

TOKEN_TTL_SECONDS = 15 * 60


def mint_room_token(session_id: int, user_id: int, secret: str, now: float | None = None) -> str:
    """Short-lived, signed room token generated by the backend. Provider secrets
    never leave the server; the token grants join permission only."""
    ts = int(now if now is not None else time.time())
    payload = f"{session_id}:{user_id}:{ts}"
    sig = hmac.new(secret.encode(), payload.encode(), hashlib.sha256).hexdigest()[:32]
    return f"{payload}:{sig}"


def verify_room_token(token: str, secret: str, now: float | None = None) -> tuple[int, int]:
    try:
        session_part, user_part, ts_part, sig = token.split(":")
        payload = f"{session_part}:{user_part}:{ts_part}"
    except ValueError:
        raise SessionError("Malformed room token.")
    expected = hmac.new(secret.encode(), payload.encode(), hashlib.sha256).hexdigest()[:32]
    if not hmac.compare_digest(expected, sig):
        raise SessionError("Invalid room token signature.")
    ts = int(ts_part)
    current = int(now if now is not None else time.time())
    if current - ts > TOKEN_TTL_SECONDS:
        raise SessionError("Room token expired — request a new one.")
    return int(session_part), int(user_part)


# ------------------------------------------------------- schedule conflicts ---

def overlaps(start_a: str, end_a: str, start_b: str, end_b: str) -> bool:
    return start_a < end_b and start_b < end_a


def find_conflicts(existing_sessions, start_at: str, end_at: str) -> list[int]:
    """Conflicts = overlapping sessions for the same teacher/class (same timeslot)."""
    conflicts = []
    for session in existing_sessions:
        if session.status in ("cancelled", "failed"):
            continue
        other_end = session.end_at or session.start_at
        if overlaps(start_at, end_at, session.start_at, other_end):
            conflicts.append(session.id)
    return conflicts


# ---------------------------------------------------------- provider policy ---


def provider_status() -> dict:
    """Live audio/video uses an established WebRTC provider (e.g. LiveKit) behind
    an adapter. With no credentials configured the integration is reported
    UNAVAILABLE — asynchronous workflows stay fully functional and no fake
    video call is ever substituted."""
    configured = bool(os.environ.get("CLASSCONNECT_WEBRTC_URL") and os.environ.get("CLASSCONNECT_WEBRTC_KEY"))
    return {
        "available": configured,
        "provider": "webrtc-adapter" if configured else None,
        "message": (
            "Live audio/video provider is configured."
            if configured
            else "Live audio/video integration is unavailable (no provider credentials configured). "
                 "Asynchronous lesson workflows remain fully available. A real call is never faked."
        ),
    }


LOW_BANDWIDTH_POLICY = {
    "video": "disable video on constrained connections; audio and text chat take priority",
    "media_quality": "reduce quality where the configured provider supports it",
    "fallback": "asynchronous lesson mode with materials, chat and follow-up space",
}


def attendance_summary(rows) -> dict:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row.state] = counts.get(row.state, 0) + 1
    return {"counts": counts, "total": len(rows)}


def poll_vote(votes_json: str, option: str, valid_options: list[str]) -> str:
    votes = json.loads(votes_json or "{}")
    if option not in valid_options:
        raise SessionError(f"Unknown poll option '{option}'.")
    votes[option] = votes.get(option, 0) + 1
    return json.dumps(votes)
