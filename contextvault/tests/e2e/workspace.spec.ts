import { test, expect } from '@playwright/test';
import { PDFDocument, StandardFonts } from 'pdf-lib';

test('register, index a PDF, ask a grounded question and inspect its source',async({page})=>{
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'Account menu'}).click();
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Test Researcher');
  const email=`test-${Date.now()}@example.com`;
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill('correct-horse-battery');
  await page.getByRole('button',{name:'Create account',exact:true}).last().click();
  await expect(page.getByRole('heading',{name:/Welcome back, Test/})).toBeVisible();
  await page.getByRole('button',{name:'New collection',exact:true}).first().click();
  const collection=page.getByRole('dialog',{name:'Create a collection'});
  await collection.getByLabel('Collection name').fill('Cobalt Research');
  await collection.getByRole('button',{name:'Create collection'}).click();
  await expect(page.getByText('Cobalt Research').first()).toBeVisible();
  await page.getByRole('button',{name:'Upload document',exact:true}).first().click();
  const upload=page.getByRole('dialog',{name:'Upload documents'});
  const pdf=await PDFDocument.create();const p=pdf.addPage();const font=await pdf.embedFont(StandardFonts.Helvetica);p.drawText('The cobalt archive protects documents with access control policies.',{x:50,y:700,font,size:12});
  await upload.locator('input[type=file]').setInputFiles({name:'cobalt.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())});
  await upload.getByRole('button',{name:'Upload documents'}).click();
  await page.getByRole('button',{name:'Documents',exact:true}).first().click();
  const row=page.locator('tr').filter({hasText:'cobalt.pdf'});await expect(row).toContainText('Ready',{timeout:30000});
  await page.getByRole('button',{name:'Conversations',exact:true}).first().click();
  await page.getByLabel('Ask a question about your documents').fill('What protects cobalt archive documents?');
  await page.getByRole('button',{name:'Send message'}).click();
  await expect(page.locator('.message-sources button').first()).toBeVisible({timeout:30000});
  await page.locator('.message-sources button').first().click();
  await expect(page.getByText('Evidence preview')).toBeVisible();
  await expect(page.locator('.source-passage')).toContainText('cobalt archive');
  await expect(page.locator('.drawer-meta')).toContainText('1');
  await page.getByRole('button',{name:'Close source preview'}).click();
  await page.getByLabel('Ask a question about your documents').fill('What does it protect?');
  await page.getByRole('button',{name:'Send message'}).click();
  await expect(page.locator('.message-assistant')).toHaveCount(2,{timeout:30000});
  await page.getByLabel('Ask a question about your documents').fill('What is the boiling point of neutronium?');
  await page.getByRole('button',{name:'Send message'}).click();
  await expect(page.getByText("I couldn't find sufficient evidence in the selected documents to answer that confidently.")).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'Account menu'}).click();
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill('correct-horse-battery');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Welcome back, Test/})).toBeVisible();
  await page.getByRole('button',{name:'Conversations',exact:true}).first().click();
  await expect(page.getByText('What protects cobalt archive documents?').first()).toBeVisible();
});

test('compare keyword, vector and hybrid retrieval in the developer playground',async({page})=>{
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'RAG Playground',exact:true}).click();
  await page.getByLabel('Playground question').fill('What is retrieval augmented generation?');
  await expect(page.getByRole('slider',{name:'Top-K chunks'})).toBeVisible();
  await expect(page.getByRole('slider',{name:'Similarity threshold'})).toBeVisible();
  const response=page.waitForResponse(r=>r.url().includes('/api/retrieval/compare')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Compare retrieval'}).click();
  expect((await response).status()).toBe(200);
  const comparison=page.getByRole('region',{name:'Retrieval comparison results'});
  await expect(comparison.getByRole('heading',{name:'Compare strategies'})).toBeVisible();
  for(const strategy of ['keyword','vector','hybrid']) await expect(comparison.getByRole('heading',{name:strategy,exact:true})).toBeVisible();
  await expect(comparison).toContainText('No answer is generated');
  await expect(comparison).toContainText('share one query embedding');
  const firstPassage=comparison.locator('.strategy-card').first().locator('summary').first();
  await expect(firstPassage).toBeVisible();await firstPassage.focus();await page.keyboard.press('Enter');
  await expect(comparison.locator('.strategy-card').first().locator('details[open] p')).not.toBeEmpty();
  await page.setViewportSize({width:390,height:844});
  const widths=await page.evaluate(()=>({viewport:window.innerWidth,document:document.documentElement.scrollWidth}));
  expect(widths.document).toBeLessThanOrEqual(widths.viewport);
  await page.getByLabel('Retrieval strategy').selectOption('keyword');
  await page.getByRole('button',{name:'Run query'}).click();
  await expect(page.getByRole('heading',{name:'Pipeline results'})).toBeVisible({timeout:30000});
  await expect(page.locator('.result-chunks')).toContainText('FTS');
});
