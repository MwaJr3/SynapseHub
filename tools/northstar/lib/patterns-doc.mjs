/**
 * Renders PATTERNS.md from the catalogue in `patterns.mjs`.
 *
 * The document is generated, not written: a test compares the file on disk with this
 * output, so the count in the first paragraph, the checked table and the list of
 * patterns that need a person can never disagree with the code. Regenerate with
 *
 *   node bin/northstar.mjs patterns --markdown > PATTERNS.md
 */
import { PATTERNS } from '../patterns.mjs';

const WORDS = {
  76: 'Seventy-six', 12: 'twelve', 13: 'thirteen', 14: 'fourteen', 1: 'one', 2: 'two', 3: 'three', 4: 'four',
  5: 'five', 6: 'six', 7: 'seven', 8: 'eight', 9: 'nine', 10: 'ten', 11: 'eleven',
};
const word = (n) => WORDS[n] ?? String(n);
const cell = (text) => String(text).replace(/\|/g, '\\|');
const codes = (list) => list.map((item) => `\`${item}\``).join(', ');
const isCanonical = (pattern) => /^P\d\d$/.test(pattern.id);

export function renderPatternsDoc() {
  const canonical = PATTERNS.filter(isCanonical);
  const extensions = PATTERNS.filter((pattern) => !isCanonical(pattern));
  const checked = PATTERNS.filter((pattern) => pattern.checks.length > 0);
  const checkedCanonical = canonical.filter((pattern) => pattern.checks.length > 0);
  const judged = PATTERNS.filter((pattern) => pattern.checks.length === 0);
  const lines = [];

  lines.push('# Pattern library', '');
  lines.push(
    '<!-- Generated by `node bin/northstar.mjs patterns --markdown`. Do not edit by hand: a test fails if this file drifts from patterns.mjs. -->',
    '',
  );
  lines.push(
    `${word(canonical.length)} canonical patterns (\`P01\`–\`P${canonical.length}\`) and ${word(extensions.length)} Northstar extensions (\`X01\`–\`X${String(extensions.length).padStart(2, '0')}\`). ` +
      `**${checkedCanonical.length}** of the ${canonical.length} canonical patterns and **${checked.length - checkedCanonical.length}** of the extensions are machine-checked from source; ` +
      `the other **${judged.length}** need a person or a browser, and are listed here so nobody claims coverage they do not have.`,
    '',
  );
  lines.push(
    'Each pattern names the skill that owns the judgement and, where it exists, the engine check that can prove a violation.',
    '',
    '## Numbering',
    '',
    '- `P01`–`P76` are the 76 patterns of the pattern write-ups, **numbered as they were supplied**. `engine/patterns.ts` uses the same numbers without the padding: `P05` here is `P5` there. The padding exists because severities are also called `P0`–`P3`, and an unpadded `P1` would be ambiguous in a report.',
    '- `X01`+ are Northstar extensions: checks the engine can make that are not among the 76 (alt text, link destinations, target size, form labels, overflow, contrast of non-text UI, …).',
    '- Reports written before the numbering was unified (v1.0.x) used a different index; the last table maps each old id to its current one.',
    '- Ids are stable: findings quote them, so a rule can change without renumbering a report someone is already reading.',
    '',
    'Run `node bin/northstar.mjs patterns` for the same list as machine-readable text.',
    '',
  );

  lines.push('## Checked patterns', '', '| Pattern | Name | Check | The standard it is held to |', '| --- | --- | --- | --- |');
  for (const pattern of checked) {
    lines.push(`| ${pattern.id} | ${cell(pattern.name)} | ${codes(pattern.checks)} | ${cell(pattern.claim)} |`);
  }
  lines.push('');

  lines.push(
    '## Patterns that need a person',
    '',
    'No automated check can settle these from source. A clean `audit` says nothing about them.',
    '',
    '| Pattern | Name | Owner | The standard it is held to |',
    '| --- | --- | --- | --- |',
  );
  for (const pattern of judged) {
    lines.push(`| ${pattern.id} | ${cell(pattern.name)} | ${pattern.skill} | ${cell(pattern.claim)} |`);
  }
  lines.push('');

  lines.push('## Old ids (v1.0.x reports)', '', '| Old id | Current id | Name |', '| --- | --- | --- |');
  for (const pattern of PATTERNS.filter((entry) => entry.legacyId).sort((a, b) => a.legacyId.localeCompare(b.legacyId))) {
    lines.push(`| ${pattern.legacyId} | ${pattern.id} | ${cell(pattern.name)} |`);
  }
  lines.push('');
  return lines.join('\n');
}
