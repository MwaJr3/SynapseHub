/**
 * Implementation Adapter — turn a UX specification into framework code while
 * preserving the same state model. The primary target is React + Tailwind
 * (the stack of this repository); acceptance checks emit Vitest + Testing
 * Library so `/ux-test` output is executable rather than aspirational.
 */
import type {
  ComponentDescriptor,
  ScreenDescriptor,
  StateMatrix,
} from './types';

// ---------------------------------------------------------------------------
// React + Tailwind component generation
// ---------------------------------------------------------------------------

export function generateReactComponent(component: ComponentDescriptor): string {
  const name = pascalCase(component.id || component.kind);
  const states = new Set(
    (component.declaredStates ?? []).map((s) => s.toLowerCase()),
  );
  const hasLoading = states.has('loading');
  const hasError = states.has('error');
  const hasDisabled = states.has('disabled');

  const props = ['variant = "primary"', 'className = ""'];
  if (hasLoading) props.push('loading = false');
  if (hasDisabled) props.push('disabled = false', 'disabledReason = ""');
  if (hasError) props.push('error = ""');
  if (component.destructive) props.push('onUndo');

  const lines: string[] = [
    `// Generated by the UX engine — state model preserved from the specification.`,
    `// Patterns: ${component.destructive ? 'P11, P48' : 'P5, P24, P28'} · Rules: STATE-COMPLETENESS-01, A11Y-FOCUS-01`,
    `export function ${name}({ ${props.join(', ')} }: {`,
    `  variant?: 'primary' | 'secondary';`,
    `  className?: string;`,
    hasLoading ? `  loading?: boolean;` : '',
    hasDisabled ? `  disabled?: boolean;` : '',
    hasDisabled ? `  disabledReason?: string;` : '',
    hasError ? `  error?: string;` : '',
    component.destructive ? `  onUndo?: () => void;` : '',
    `  children: React.ReactNode;`,
    `  onClick?: () => void;`,
    `}) {`,
  ];

  if (hasLoading) {
    lines.push(
      `  // P28: truthful busy semantics, focus preserved, duplicate actions blocked.`,
    );
    lines.push(`  if (loading) {`);
    lines.push(`    return (`);
    lines.push(
      `      <button type="button" className="btn btn-primary opacity-70" aria-busy="true" disabled>`,
    );
    lines.push(
      `        <span className="size-4 animate-spin rounded-full border-2 border-current border-t-transparent" aria-hidden="true" />`,
    );
    lines.push(`        <span className="sr-only">Loading, please wait</span>`);
    lines.push(`        {children}`);
    lines.push(`      </button>`);
    lines.push(`    );`);
    lines.push(`  }`);
  }

  if (hasDisabled) {
    lines.push(
      `  // P5: reachable explanation — aria-disabled keeps the control focusable.`,
    );
    lines.push(`  if (disabled) {`);
    lines.push(`    return (`);
    lines.push(`      <button`);
    lines.push(`        type="button"`);
    lines.push(`        aria-disabled="true"`);
    lines.push(
      `        aria-describedby={disabledReason ? \`\${'${name.toLowerCase()}-reason'}\` : undefined}`,
    );
    lines.push(
      `        className="btn btn-secondary cursor-not-allowed opacity-60"`,
    );
    lines.push(`        onClick={(event) => event.preventDefault()}`);
    lines.push(`      >`);
    lines.push(`        {children}`);
    lines.push(
      `        {disabledReason && <span id="${name.toLowerCase()}-reason" className="sr-only">{disabledReason}</span>}`,
    );
    lines.push(`      </button>`);
    lines.push(`    );`);
    lines.push(`  }`);
  }

  lines.push(`  return (`);
  lines.push(`    <button`);
  lines.push(`      type="button"`);
  if (component.destructive) {
    lines.push(
      `      className={\`btn \${variant === 'primary' ? 'bg-red-600 text-white' : 'btn-secondary'} \${className}\`}`,
    );
  } else {
    lines.push(
      `      className={\`btn \${variant === 'primary' ? 'btn-primary' : 'btn-secondary'} \${className}\`}`,
    );
  }
  lines.push(`      onClick={onClick}`);
  if (hasError) lines.push(`      aria-invalid={Boolean(error)}`);
  if (hasError)
    lines.push(
      `      aria-describedby={error ? \`\${'${name.toLowerCase()}-error'}\` : undefined}`,
    );
  lines.push(`    >`);
  lines.push(`      {children}`);
  if (component.destructive) {
    lines.push(`      {onUndo && (`);
    lines.push(
      `        <span className="ml-2 text-button" role="button" tabIndex={0} onClick={onUndo} onKeyDown={(e) => e.key === 'Enter' && onUndo()}>`,
    );
    lines.push(`          Undo`);
    lines.push(`        </span>`);
    lines.push(`      )}`);
  }
  lines.push(`    </button>`);
  if (hasError) {
    lines.push(`  );`);
    lines.push(
      `  // P23: what happened, why it matters, next action — rendered beside the control.`,
    );
    lines.push(
      `  // {error && <p id="${name.toLowerCase()}-error" role="alert" className="text-sm text-red-600">{error}</p>}`,
    );
  } else {
    lines.push(`  );`);
  }
  lines.push(`}`);

  return lines.filter((line) => line !== undefined).join('\n');
}

// ---------------------------------------------------------------------------
// Acceptance checks — executable UX test scaffold
// ---------------------------------------------------------------------------

export interface AcceptanceCheck {
  id: string;
  title: string;
  patternIds: string[];
  testCode: string;
}

export function generateAcceptanceChecks(
  screen: ScreenDescriptor,
  matrix?: StateMatrix,
): AcceptanceCheck[] {
  const checks: AcceptanceCheck[] = [
    {
      id: 'AC-KEYBOARD',
      title: 'Every action is reachable and operable with the keyboard alone',
      patternIds: ['P46', 'P20'],
      testCode: [
        `it('completes the primary task with keyboard only', async () => {`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  await user.tab();`,
        `  expect(document.activeElement).not.toBe(document.body);`,
        `  await user.keyboard('{Enter}');`,
        `  expect(screen.getByRole('status')).toBeInTheDocument();`,
        `});`,
      ].join('\n'),
    },
    {
      id: 'AC-FOCUS',
      title:
        'Focus-visible ring is present and overlays trap and restore focus',
      patternIds: ['P46', 'P65'],
      testCode: [
        `it('traps focus in overlays and restores it on close', async () => {`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  await user.click(screen.getByRole('button', { name: /open/i }));`,
        `  const dialog = await screen.findByRole('dialog');`,
        `  expect(dialog).toHaveFocus();`,
        `  await user.keyboard('{Escape}');`,
        `  expect(screen.queryByRole('dialog')).not.toBeInTheDocument();`,
        `});`,
      ].join('\n'),
    },
    {
      id: 'AC-CONTRAST',
      title: 'Text and UI pairs meet WCAG AA contrast in both themes',
      patternIds: ['P70', 'P55'],
      testCode: [
        `it.each(['light', 'dark'])('passes AA contrast in %s theme', (theme) => {`,
        `  for (const [fg, bg, required] of contrastPairs(theme)) {`,
        `    expect(contrastRatio(fg, bg)).toBeGreaterThanOrEqual(required);`,
        `  }`,
        `});`,
      ].join('\n'),
    },
    {
      id: 'AC-TARGET',
      title: 'Interactive targets are at least 44x44px on coarse pointers',
      patternIds: ['P6', 'P33'],
      testCode: [
        `it('keeps touch targets >= 44px', () => {`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  for (const control of screen.getAllByRole('button')) {`,
        `    const rect = control.getBoundingClientRect();`,
        `    expect(Math.min(rect.width, rect.height)).toBeGreaterThanOrEqual(44);`,
        `  }`,
        `});`,
      ].join('\n'),
    },
  ];

  const states = new Set<string>();
  for (const component of screen.components) {
    (component.declaredStates ?? []).forEach((state) =>
      states.add(state.toLowerCase()),
    );
  }

  if (states.has('loading')) {
    checks.push({
      id: 'AC-LOADING',
      title:
        'Loading state is truthful, announces busy status and blocks duplicate actions',
      patternIds: ['P28', 'P54', 'P18'],
      testCode: [
        `it('announces busy state and blocks duplicate submissions', async () => {`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  await user.click(screen.getByRole('button', { name: /save/i }));`,
        `  expect(await screen.findByRole('button', { busy: true })).toBeInTheDocument();`,
        `  await user.click(screen.getByRole('button', { busy: true }));`,
        `  expect(submitMock).toHaveBeenCalledTimes(1);`,
        `});`,
      ].join('\n'),
    });
  }

  if (states.has('error')) {
    checks.push({
      id: 'AC-ERROR',
      title: 'Errors explain the failure and offer a working recovery action',
      patternIds: ['P23', 'P51'],
      testCode: [
        `it('surfaces an actionable error and preserves input', async () => {`,
        `  server.use(http.post('/api', () => HttpResponse.error()));`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  await user.type(screen.getByLabelText(/name/i), 'Ada');`,
        `  await user.click(screen.getByRole('button', { name: /save/i }));`,
        `  const alert = await screen.findByRole('alert');`,
        `  expect(alert).toHaveTextContent(/try again/i);`,
        `  expect(screen.getByLabelText(/name/i)).toHaveValue('Ada');`,
        `});`,
      ].join('\n'),
    });
  }

  if (screen.components.some((c) => c.undoAvailable || c.destructive)) {
    checks.push({
      id: 'AC-UNDO',
      title: 'Destructive work is reversible through an undo window',
      patternIds: ['P48', 'P11'],
      testCode: [
        `it('restores destroyed work through undo', async () => {`,
        `  render(<${pascalCase(screen.id)}Screen />);`,
        `  await user.click(screen.getByRole('button', { name: /delete/i }));`,
        `  await user.click(await screen.findByRole('button', { name: /undo/i }));`,
        `  expect(screen.getByText(/restored/i)).toBeInTheDocument();`,
        `});`,
      ].join('\n'),
    });
  }

  if (screen.reducedMotionSupported) {
    checks.push({
      id: 'AC-REDUCED-MOTION',
      title:
        'Reduced-motion preference removes animation without losing meaning',
      patternIds: ['P9', 'P68'],
      testCode: [
        `it('honours prefers-reduced-motion', () => {`,
        `  matchMediaStub('(prefers-reduced-motion: reduce)', true);`,
        `  const { container } = render(<${pascalCase(screen.id)}Screen />);`,
        `  expect(container.querySelector('[data-animated]')).toBeNull();`,
        `  expect(screen.getByText(/complete/i)).toBeInTheDocument();`,
        `});`,
      ].join('\n'),
    });
  }

  if (matrix) {
    checks.push({
      id: 'AC-STATE-MATRIX',
      title: `Every declared ${matrix.componentKind} state is reachable in tests`,
      patternIds: ['P24', 'P28'],
      testCode: [
        `it.each(${JSON.stringify(matrix.requiredStates)})('reaches the %s state', async (state) => {`,
        `  const harness = renderHarness(${pascalCase(matrix.componentKind)}Spec);`,
        `  await harness.drive(state);`,
        `  expect(harness.matchesState(state)).toBe(true);`,
        `});`,
      ].join('\n'),
    });
  }

  return checks;
}

function pascalCase(value: string): string {
  return (
    value
      .split(/[^a-zA-Z0-9]+/)
      .filter(Boolean)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join('') || 'Component'
  );
}
