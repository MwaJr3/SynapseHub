/** Look up a pattern by id. */
export function patternById(id) {
  return PATTERNS.find((pattern) => pattern.id === id) ?? null;
}

/** Which patterns have no automated check, and therefore need eyes. */
export function unautomated() {
  return PATTERNS.filter((pattern) => pattern.checks.length === 0).map((pattern) => pattern.id);
}
