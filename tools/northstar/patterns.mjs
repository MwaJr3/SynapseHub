/** Look up a pattern by id. */
export function patternById(id) {
  return PATTERNS.find((pattern) => pattern.id === id) ?? null;
}

/** Translate an id from before the numbering was unified (v1.0.x reports). */
export function patternByLegacyId(id) {
  return PATTERNS.find((pattern) => pattern.legacyId === id) ?? null;
}

/** The engine/patterns.ts id for a CLI id (`P05` → `P5`); extensions have none. */
export function engineId(id) {
  return /^P\d\d$/.test(id) ? 'P' + Number(id.slice(1)) : null;
}

/** Which patterns have no automated check, and therefore need eyes. */
export function unautomated() {
  return PATTERNS.filter((pattern) => pattern.checks.length === 0).map((pattern) => pattern.id);
}
