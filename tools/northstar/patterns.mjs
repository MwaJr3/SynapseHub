/**
 * The pattern library.
 *
 * These are the interaction patterns the engine is built around: what each one is
 * for, which engine check can prove a violation from source, and which skill owns
 * the judgement that a check cannot make. The numbering is Northstar's own index
 * and is stable — findings quote it, so a rule change never silently renumbers a
 * report a user is already reading.
 *
 * A pattern with an empty `checks` list is not a gap: it is a pattern that cannot
 * be settled without looking at the rendered page, and saying so is more useful
 * than pretending to measure it.
 */

